import { getAgentConfig, validateAgentState } from '../config/agent.config.js';
import gitDiffTracker from '../utils/gitDiffTracker.js';

/**
 * Middleware to prevent agents from getting stuck in plan mode
 * Automatically enforces execution mode and includes git diffs
 */

// Track agent requests to detect plan mode loops
const agentRequestTracker = new Map();

/**
 * Detect which agent is making the request
 */
const detectAgent = (req) => {
  const userAgent = req.headers['user-agent'] || '';
  const agentHeader = req.headers['x-agent-name'] || '';
  const agentParam = req.query.agent || '';

  // Check explicit headers/params first
  if (agentHeader) return agentHeader.toLowerCase();
  if (agentParam) return agentParam.toLowerCase();

  // Detect from user-agent string
  if (userAgent.toLowerCase().includes('blackbox')) return 'blackbox';
  if (userAgent.toLowerCase().includes('claude')) return 'claude';
  if (userAgent.toLowerCase().includes('cursor')) return 'cursor';
  if (userAgent.toLowerCase().includes('copilot')) return 'copilot';

  return 'default';
};

/**
 * Main middleware to enforce execution mode
 */
export const enforceExecutionMode = async (req, res, next) => {
  try {
    const agentName = detectAgent(req);
    const config = getAgentConfig(agentName);

    // Add agent info to request
    req.agent = {
      name: agentName,
      config,
      timestamp: Date.now()
    };

    // Track request
    const sessionId = req.headers['x-session-id'] || req.ip;
    const tracker = agentRequestTracker.get(sessionId) || {
      requests: 0,
      lastRequest: 0,
      planModeCount: 0
    };

    tracker.requests++;
    tracker.lastRequest = Date.now();

    // Detect plan mode loop (multiple requests without execution)
    const timeSinceLastRequest = Date.now() - tracker.lastRequest;
    if (timeSinceLastRequest < 1000 && tracker.requests > 3) {
      tracker.planModeCount++;

      if (tracker.planModeCount > config.behavior.maxPlanIterations) {
        // Force execution mode
        req.forcedExecutionMode = true;
        req.planModeWarning = 'Agent stuck in plan mode - forcing execution';
      }
    } else {
      tracker.planModeCount = 0;
    }

    agentRequestTracker.set(sessionId, tracker);

    // Add execution mode headers to response
    res.setHeader('X-Agent-Mode', 'execute');
    res.setHeader('X-Plan-Mode', 'disabled');
    res.setHeader('X-Require-Response', 'true');
    res.setHeader('X-Include-Git-Diff', 'true');

    next();
  } catch (error) {
    console.error('Agent middleware error:', error);
    next(); // Continue even if middleware fails
  }
};

/**
 * Middleware to automatically include git diff in responses
 */
export const autoIncludeGitDiff = async (req, res, next) => {
  const originalJson = res.json.bind(res);

  res.json = async function (data) {
    try {
      const config = req.agent?.config || getAgentConfig('default');

      // If config requires git diff and it's not already included
      if (config.gitDiff.includeInResponse && !data.gitDiff) {
        const gitDiff = await gitDiffTracker.getCurrentDiff();

        return originalJson({
          ...data,
          gitDiff,
          agentMode: 'execute',
          planMode: 'disabled',
          metadata: {
            ...data.metadata,
            gitDiffIncluded: true,
            autoGenerated: true
          }
        });
      }

      return originalJson(data);
    } catch (error) {
      console.error('Error including git diff:', error);
      return originalJson(data);
    }
  };

  next();
};

/**
 * Middleware to validate agent responses
 * Ensures responses include required fields
 */
export const validateAgentResponse = (req, res, next) => {
  const originalJson = res.json.bind(res);

  res.json = function (data) {
    const config = req.agent?.config || getAgentConfig('default');
    const required = config.response.required || ['message', 'status'];

    // Check if response has required fields
    const missing = required.filter(field => !(field in data));

    if (missing.length > 0) {
      // Add missing fields with defaults
      if (!data.message) data.message = 'Operation completed';
      if (!data.status) data.status = 'success';
      if (!data.gitDiff && config.gitDiff.includeInResponse) {
        data.gitDiff = '(will be added by autoIncludeGitDiff middleware)';
      }
    }

    // Add execution mode markers
    return originalJson({
      ...data,
      agentMode: 'execute',
      planModeDisabled: true,
      timestamp: data.timestamp || new Date().toISOString()
    });
  };

  next();
};

/**
 * Middleware to detect and prevent plan mode timeouts
 */
export const preventPlanModeTimeout = (req, res, next) => {
  const config = req.agent?.config || getAgentConfig('default');
  const timeout = config.timeout.planMode;

  // Set timeout to force response
  const timer = setTimeout(() => {
    if (!res.headersSent) {
      console.warn('[Agent Middleware] Plan mode timeout - forcing response');

      res.status(408).json({
        success: false,
        error: 'Plan mode timeout',
        message: 'Agent took too long in plan mode - execution forced',
        recommendation: 'Switch to execution mode immediately',
        agentMode: 'execute',
        planMode: 'disabled'
      });
    }
  }, timeout);

  // Clear timeout when response is sent
  res.on('finish', () => {
    clearTimeout(timer);
  });

  next();
};

/**
 * Cleanup old tracking data
 */
setInterval(() => {
  const now = Date.now();
  const maxAge = 5 * 60 * 1000; // 5 minutes

  for (const [sessionId, tracker] of agentRequestTracker.entries()) {
    if (now - tracker.lastRequest > maxAge) {
      agentRequestTracker.delete(sessionId);
    }
  }
}, 60000); // Clean every minute

export default {
  enforceExecutionMode,
  autoIncludeGitDiff,
  validateAgentResponse,
  preventPlanModeTimeout
};
